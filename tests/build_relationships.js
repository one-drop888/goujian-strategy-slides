#!/usr/bin/env node
'use strict';
const fs=require('fs');
const os=require('os');
const path=require('path');
const crypto=require('crypto');
const {execFileSync}=require('child_process');
const {buildDeck}=require('../core/renderer');
const canonical=require('../skill/examples/v1.3/relationships-deck.json');

const ROOT=path.resolve(__dirname,'..');
const HOME=os.homedir();
const DEFAULT_OUT=path.join(ROOT,'out/v13-control/relationships');
const FIXTURE=path.join(ROOT,'skill/examples/v1.3/relationships-deck.json');
const MARKER='.goujian-relationships-output';
const PROFILES=[['light','executive-clean'],['dark','dark-executive']];
const CASES=[['dated-timeline',0],['dated-timeline-close',1],['branch-swimlane',2],['roadmap',3]];
const PYTHON=process.env.GOUJIAN_PYTHON||'python3';

const sha256=file=>crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const rel=file=>path.relative(ROOT,file).split(path.sep).join('/');
const writeJson=(file,value)=>{fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,JSON.stringify(value,null,2)+'\n');};
const readJson=file=>JSON.parse(fs.readFileSync(file,'utf8'));
const sanitizeText=value=>String(value)
  .split(ROOT+path.sep).join('')
  .split(ROOT).join('.')
  .split(os.tmpdir()+path.sep).join('$TMP/')
  .split(HOME+path.sep).join('~/')
  .split(HOME).join('~');
const sanitizeValue=value=>{
  if(typeof value==='string') return sanitizeText(value);
  if(Array.isArray(value)) return value.map(sanitizeValue);
  if(value&&typeof value==='object') return Object.fromEntries(Object.entries(value).map(([key,item])=>[sanitizeText(key),sanitizeValue(item)]));
  return value;
};
const sanitizeJsonFile=file=>{
  if(!fs.existsSync(file)) return null;
  const data=readJson(file),clean=sanitizeValue(data);
  if(JSON.stringify(clean)!==JSON.stringify(data)) writeJson(file,clean);
  return clean;
};

function parseArgs(argv){
  let outRoot=DEFAULT_OUT;
  for(let index=0;index<argv.length;index++){
    if(argv[index]==='--out-root') outRoot=path.resolve(argv[++index]);
    else if(argv[index]==='--help'||argv[index]==='-h'){console.log('usage: node tests/build_relationships.js [--out-root DIR]');process.exit(0);}
    else throw new Error(`Unknown argument ${argv[index]}`);
  }
  return {outRoot};
}

function prepareOutDir(outDir){
  if(fs.existsSync(outDir)){
    const entries=fs.readdirSync(outDir);
    const owned=entries.every(name=>name===MARKER||name==='manifest.json'||name==='render'||name==='qa'||/\.(pptx|json)$/.test(name));
    if(!owned) throw new Error(`Refusing to replace an unrecognized directory: ${outDir}`);
    fs.rmSync(outDir,{recursive:true,force:true});
  }
  fs.mkdirSync(outDir,{recursive:true});
  fs.writeFileSync(path.join(outDir,MARKER),'Generated by tests/build_relationships.js from skill/examples/v1.3/relationships-deck.json\n');
}

function sceneEvidence(name,scene){
  const nodes=role=>scene.nodes.filter(node=>node.semantic_role===role);
  if(name.startsWith('dated-timeline')) return {
    markers:nodes('timeline_marker').length,
    marker_positions:nodes('timeline_marker').map(node=>({id:node.node_id,x:node.bbox?.x,label_lane:node.label_lane??0})),
    date_labels:nodes('timeline_date').map(node=>node.text),
    durations:nodes('timeline_duration').map(node=>({id:node.node_id,days:node.duration_days})),
    leaders:nodes('timeline_leader').map(node=>node.node_id)
  };
  if(name==='branch-swimlane') return {
    task_nodes:nodes('task_node').map(node=>({id:node.task_id,owner:node.owner,date:node.date,status:node.status})),
    swimlane_labels:nodes('swimlane_label').map(node=>node.text),
    decision_edges:nodes('decision_edge').map(node=>node.text),
    dependencies:nodes('dependency').map(node=>({from:node.from,to:node.to}))
  };
  return {lane_headings:scene.nodes.filter(node=>node.kind==='text'&&['产品','运营','研究'].includes(node.text)).map(node=>node.text)};
}

function qaSummary(report){
  const checks=report.checks||{};
  return Object.fromEntries(Object.entries(checks).map(([key,value])=>[key,value?.status||'UNKNOWN']));
}

async function main(){
  const {outRoot:outDir}=parseArgs(process.argv.slice(2));
  prepareOutDir(outDir);
  const outputs=[];
  let failed=false;
  for(const [theme,profile] of PROFILES){
    for(const [name,index] of CASES){
      const slide=canonical.slides[index];
      const base=`${name}-${theme}`;
      const specPath=path.join(outDir,`${base}.spec.json`);
      const pptxPath=path.join(outDir,`${base}.pptx`);
      const qaPath=path.join(outDir,'qa',`${base}.qa.json`);
      const renderDir=path.join(outDir,'render',base);
      writeJson(specPath,{schema_version:canonical.schema_version,title:canonical.title,slides:[slide]});
      const result=await buildDeck(readJson(specPath),pptxPath,{profile});
      const scene=readJson(pptxPath+'.scene.json').slides[0];
      let qaStatus='FAIL',qaError=null,qa=null;
      try {
        const args=[path.join(ROOT,'skill/scripts/quality_gate.py'),pptxPath,'--spec',specPath,'--out',qaPath,
          '--render-dir',renderDir,'--scene',pptxPath+'.scene.json','--profile',profile];
        execFileSync(PYTHON,args,{cwd:ROOT,encoding:'utf8',stdio:['ignore','pipe','pipe'],timeout:420000});
        qa=sanitizeJsonFile(qaPath);
        sanitizeJsonFile(qaPath.replace(/\.json$/,'.semantic-qa.json'));
        qaStatus=qa.status;
      } catch(error){
        qaError=(error.stderr||error.message||'').toString().trim().split('\n').slice(-3).join(' | ');
        qaError=qaError?sanitizeText(qaError):null;
        if(fs.existsSync(qaPath)) {try{qa=sanitizeJsonFile(qaPath);qaStatus=qa.status;}catch{}}
        sanitizeJsonFile(qaPath.replace(/\.json$/,'.semantic-qa.json'));
      }
      const render=qa?.checks?.render;
      const pages=(render?.pages||[]).map((page,pageIndex)=>({page:pageIndex+1,path:rel(page),sha256:sha256(page)}));
      const montage=render?.montage&&fs.existsSync(render.montage)?{path:rel(render.montage),sha256:sha256(render.montage)}:null;
      const pdf=render?.pdf&&fs.existsSync(render.pdf)?{path:rel(render.pdf),sha256:sha256(render.pdf)}:null;
      const passed=qaStatus!=='FAIL'&&render?.status==='PASS'&&pages.length===1&&montage;
      if(!passed) failed=true;
      outputs.push({
        case:name,theme,profile,
        pptx:{path:rel(pptxPath),sha256:sha256(pptxPath)},
        spec:{path:rel(specPath),sha256:sha256(specPath)},
        scene:{path:rel(pptxPath+'.scene.json'),sha256:sha256(pptxPath+'.scene.json')},
        build:{profile:result.profile,slides:result.slides},
        evidence:sceneEvidence(name,scene),
        qa:{path:rel(qaPath),sha256:fs.existsSync(qaPath)?sha256(qaPath):null,status:qaStatus,checks:qa?qaSummary(qa):{},error:qaError},
        render:{status:render?.status||'FAIL',pages,montage,pdf}
      });
      console.log(`${passed?'PASS':'FAIL'} ${base} qa=${qaStatus} render=${render?.status||'FAIL'} pages=${pages.length}`);
    }
  }
  const manifest={
    schema_version:'1.3',
    status:failed?'FAIL':'PASS',
    visual_qa:'NOT_RUN',
    fixture:{path:rel(FIXTURE),sha256:sha256(FIXTURE)},
    note:'Every native PPTX is built from the shared V1.3 fixture, rendered and montaged by quality_gate.py via LibreOffice/pdftoppm, and structurally QA-checked. No visual approval is claimed; an independent reviewer must inspect the pages.',
    outputs
  };
  writeJson(path.join(outDir,'manifest.json'),manifest);
  console.log(JSON.stringify({status:manifest.status,visual_qa:manifest.visual_qa,outputs:outputs.length,manifest:rel(path.join(outDir,'manifest.json'))},null,2));
  if(failed) process.exitCode=2;
}

main().catch(error=>{console.error(error.stack||error);process.exitCode=1;});
